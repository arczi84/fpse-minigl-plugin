/* Lightweight display-rate meter. No timer, GL, logging or Amiga calls here. */
#ifndef FPSE_MINIGL_FPS_COUNTER_H
#define FPSE_MINIGL_FPS_COUNTER_H
#include <stdint.h>
#include <stdio.h>

typedef struct {
    uint32_t sec, usec, last_display_count, presents;
    uint32_t shown10, emulated10;
} MGLFpsCounter;

static void mgl_fps_reset(MGLFpsCounter *s, uint32_t sec, uint32_t usec,
    uint32_t display_count)
{
    s->sec = sec; s->usec = usec; s->last_display_count = display_count;
    s->presents = s->shown10 = s->emulated10 = 0;
}

static void mgl_fps_present(MGLFpsCounter *s) { ++s->presents; }

/* Samples the preceding interval; nf is updateDisplay's counter BEFORE
 * frame skipping, just as in gpupeops/amiga_disp.c. It is not GPU_Update,
 * CPU emulation speed or a count of unique images generated by the game. */
static int mgl_fps_sample(MGLFpsCounter *s, uint32_t sec, uint32_t usec,
    uint32_t display_count)
{
    uint32_t seconds = sec - s->sec;
    uint64_t elapsed;
    if (seconds > UINT32_C(0x7fffffff) || (!seconds && usec < s->usec)) {
        mgl_fps_reset(s, sec, usec, display_count);
        return 0;
    }
    /* Most calls avoid all 64-bit arithmetic. Reuse the limiter's clock. */
    if (!seconds || (seconds == 1 && usec < s->usec)) return 0;
    elapsed = (uint64_t)seconds * UINT32_C(1000000) + usec - s->usec;
    s->shown10 = (uint32_t)(((uint64_t)s->presents * UINT32_C(10000000)
        + elapsed / 2) / elapsed);
    s->emulated10 = (uint32_t)(((uint64_t)(uint32_t)(display_count - s->last_display_count)
        * UINT32_C(10000000) + elapsed / 2) / elapsed);
    s->sec = sec; s->usec = usec; s->last_display_count = display_count;
    s->presents = 0;
    return 1;
}

static void mgl_fps_title(const MGLFpsCounter *s, char *title, size_t length)
{
    snprintf(title, length, "FPSE - MiniGL | FPS %lu.%lu | emu %lu.%lu",
        (unsigned long)(s->shown10 / 10), (unsigned long)(s->shown10 % 10),
        (unsigned long)(s->emulated10 / 10), (unsigned long)(s->emulated10 % 10));
}
#endif

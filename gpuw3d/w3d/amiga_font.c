static void print_packed_char(unsigned char *dst, int bpr, int bpp, unsigned char c)
{
  unsigned char *src = (unsigned char *)packed_charset;
  int x, y, z;
  int row = (c >> 5) * ((160 / 8) * 8);
  int col = (c & 31) * 5;
  int shift = col & 7;
  col >>= 3;

  for (y=0; y<8; y++) {
    unsigned short val = *(unsigned short *)(src + row + col);
    val <<= shift;
    for (x=0; x<5; x++) {
      for (z=0; z<bpp; z++) {
        *dst++ = (val & 0x8000) ? 0xff : 0x00;
      }
      val <<= 1;
    }
    row += (160 / 8);
    dst += bpr - (bpp * 5);
  }
}

static void print_packed_string(unsigned char *dst, int bpr, int bpp, char *str)
{
  while (*str) {
    print_packed_char(dst, bpr, bpp, *str);
    dst += (5 * bpp);
    str++;
  }
}

text_line_t text_lines[NUM_TEXT_LINES];

static void print_text_lines(void)
{
  char c;
  int y;

  /* Anything to print ? */
  c = 0;
  for (y=0; y<NUM_TEXT_LINES; y++) {
    c |= text_lines[y].text[0];
  }
  if (c == 0) return;

  /* Print text */
#ifdef __amigaos4__
  if ((lock = p96LockBitMap(window_bitmap, (UBYTE *)&ri, sizeof(ri)))) {
    for (y=0; y<NUM_TEXT_LINES; y++) {
      print_packed_string((UBYTE *)ri.Memory + (y * (8 + 2) * bpr), bpr, bpp, text_lines[y].text);
    }
    p96UnlockBitMap(window_bitmap, lock);
  }
#else
  if ((lock = LockBitMapTags(window_bitmap, LBMI_BASEADDRESS, (ULONG)&baseaddress, TAG_END))) {
    for (y=0; y<NUM_TEXT_LINES; y++) {
      print_packed_string((UBYTE *)baseaddress + (y * (8 + 2) * bpr), bpr, bpp, text_lines[y].text);
    }
    UnLockBitMap(lock);
  }
#endif

  /* Any autohide ? */
  for (y=0; y<NUM_TEXT_LINES; y++) {
    if (text_lines[y].autohide != 0.0) {
      amidog_timeval_t ct;
      double titi;
      timer_gettime(timer, &ct);
      titi  = (double)((signed int)ct.sec-(signed int)text_lines[y].st.sec);
      titi += (double)((signed int)ct.usec-(signed int)text_lines[y].st.usec)/1000000.0;
      if (titi > text_lines[y].autohide) {
        text_lines[y].text[0] = 0;
      }
    }
  }
}

void GPU_InfoDisplay(GPU_InfoDisplayType *nfo)
{
  if (nfo->version == (GPU_INFODISPLAY_VERSION | GPU_INFODISPLAY_PRINTF)) {
    strcpy(text_lines[GPU_INFO_LINE].text, nfo->text);
    text_lines[GPU_INFO_LINE].autohide = 2.0;
    timer_gettime(timer, &text_lines[GPU_INFO_LINE].st);
  }
}
